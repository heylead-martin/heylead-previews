// dist/_redirects = generated retired rules + public/_redirects (static before dynamic).
export const redirectsFile = (published = new Set(), staticRules = '') =>
  `# Generated by the build (astro.config.mjs) from src/config/retired.mjs and public/_redirects.\n# Retired listings\n${retiredRedirects(published).join('\n')}\n\n${staticRules.trim()}\n`;

// Syntax and limits (Cloudflare Pages): "source destination [status]", statuses 301/302/303/307/308
// (200 for rewrites), at most 2,000 static and 100 dynamic rules, 1,000 characters per line,
// static before dynamic, no duplicate sources.
export function validateRedirects(text) {
  const problems = [];
  const rules = text.split('\n').map((line, i) => ({line: line.trim(), n: i + 1})).filter(r => r.line && !r.line.startsWith('#'));
  const seen = new Set();
  let staticCount = 0, dynamicCount = 0, sawDynamic = false;
  for (const {line, n} of rules) {
    if (line.length > 1000) problems.push(`line ${n}: over 1,000 characters`);
    const parts = line.split(/\s+/);
    if (parts.length < 2 || parts.length > 3) { problems.push(`line ${n}: expected "source destination [status]"`); continue; }
    const [from, to, status = '302'] = parts;
    if (!from.startsWith('/')) problems.push(`line ${n}: source must be a path (domain-level redirects are not supported)`);
    if (!/^(?:\/|https:\/\/)/.test(to)) problems.push(`line ${n}: destination must be a path or https URL`);
    if (!['301', '302', '303', '307', '308', '200'].includes(status)) problems.push(`line ${n}: unsupported status ${status}`);
    if ((from.match(/\*/g) || []).length > 1) problems.push(`line ${n}: more than one splat`);
    if (seen.has(from)) problems.push(`line ${n}: duplicate source ${from}`);
    seen.add(from);
    const dynamic = /[*:]/.test(from);
    if (dynamic) { dynamicCount++; sawDynamic = true; } else { staticCount++; if (sawDynamic) problems.push(`line ${n}: static rule after a dynamic rule`); }
  }
  if (staticCount > 2000) problems.push(`${staticCount} static rules (limit 2,000)`);
  if (dynamicCount > 100) problems.push(`${dynamicCount} dynamic rules (limit 100)`);
  return {problems, staticCount, dynamicCount};
}
