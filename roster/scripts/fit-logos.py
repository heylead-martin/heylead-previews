"""Measure logo artwork and emit CSS framing. Original image bytes stay intact."""
import json
from pathlib import Path
import re

from PIL import Image, ImageChops


def measure(image):
    rgba = image.convert('RGBA')
    width, height = rgba.size
    red, green, blue, alpha = rgba.split()
    visible = alpha.point(lambda value: 255 if value > 8 else 0)
    bounds = visible.getbbox()
    if not bounds:
        return None
    transparent = alpha.getextrema()[0] < 128
    darkest = ImageChops.darker(ImageChops.darker(red, green), blue)
    if not transparent:
        # Only trim a near-white canvas when its entire outer border is white.
        foreground = darkest.point(lambda value: 255 if value < 245 else 0)
        edges = [(0, 0, width, 1), (0, height - 1, width, height),
                 (0, 0, 1, height), (width - 1, 0, width, height)]
        if all(not foreground.crop(edge).getbbox() for edge in edges):
            bounds = foreground.getbbox() or bounds
    solid = alpha.point(lambda value: 255 if value > 128 else 0)
    light = ImageChops.multiply(solid, darkest.point(lambda value: 255 if value > 210 else 0))
    dark_background = transparent and light.histogram()[255] > solid.histogram()[255] * .7
    left, top, right, bottom = bounds
    # Keep a little breathing room around antialiased edges, without cutting off artwork.
    guard = max(1, round(max(right - left, bottom - top) * .015))
    left, top = max(0, left - guard), max(0, top - guard)
    right, bottom = min(width, right + guard), min(height, bottom + guard)
    # Wide wordmarks get a wider tile so their lettering is not squeezed into a square.
    ratio = 1.5 if (right - left) / (bottom - top) > 2 else 1
    scale = 88 / max((right - left) / ratio, bottom - top)
    return {
        'ratio': ratio,
        'width': round(width * scale / ratio, 3), 'height': round(height * scale, 3),
        'x': round(50 + (width - left - right) * scale / (2 * ratio), 3),
        'y': round(50 + (height - top - bottom) * scale / 2, 3),
        'dark': dark_background, 'bounds': [left, top, right, bottom],
        'trimmed': [left, top, right, bottom] != [0, 0, width, height],
    }


def stylesheet(root):
    presentation = json.loads((root / 'data/presentation.json').read_text())
    companies = json.loads((root / 'data/companies.json').read_text())['companies']
    sources = sorted({presentation.get(company['slug'], {}).get('logo', '') for company in companies} - {''})
    # Pages serve the WebP copies from optimize-logos.py; key each rule on the served path.
    variants_file = root / 'data/logo-variants.json'
    served = {src: v['src'] for src, v in json.loads(variants_file.read_text()).items()} if variants_file.exists() else {}
    rules = ['/* Generated by scripts/fit-logos.py. CSS only; source assets are unchanged. */']
    counts = {'measured': 0, 'trimmed': 0, 'wide': 0, 'darkBackgrounds': 0, 'vectors': 0}
    for src in sources:
        if not re.fullmatch(r'/roster/assets/(?:logos|companies)/[A-Za-z0-9_.-]+', src):
            raise ValueError(f'Unexpected local logo path: {src}')
        file = root / src.removeprefix('/roster/')
        if file.suffix.lower() == '.svg':
            counts['vectors'] += 1
            continue
        with Image.open(file) as image:
            fit = measure(image)
        if fit is None:
            continue
        counts['measured'] += 1
        counts['trimmed'] += fit['trimmed']
        counts['wide'] += fit['ratio'] > 1
        counts['darkBackgrounds'] += fit['dark']
        if not fit['trimmed'] and not fit['dark'] and fit['ratio'] == 1:
            continue
        values = ';'.join(f'--logo-{key}:{fit[key]}%' for key in ('width', 'height', 'x', 'y'))
        if fit['ratio'] > 1:
            values += f';--logo-ratio:{fit["ratio"]}'
        if fit['dark']:
            values += ';--logo-background:#243b32'
        rules.append(f'.listing-logo.has-logo:has(img[src="{served.get(src, src)}"]){{{values}}}')
    return '\n'.join(rules) + '\n', counts


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    css, counts = stylesheet(root)
    (root / 'assets/logo-fit.css').write_text(css)
    print(json.dumps(counts))
