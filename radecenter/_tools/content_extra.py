ALPHABET = "АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЮЯ"
TYPO = [("нераз- положения", "неразположения"), ("жлъчният мехур", "жлъчния мехур"), ("бъдещето.Не", "бъдещето. Не"),
        ("Ура ,", "Ура,"), ("на моят живот", "на моя живот"), ("„Има ли смисъл”?", "„Има ли смисъл?“")]


def clean(t):
    for a, b in TYPO:
        t = t.replace(a, b)
    t = t.replace("\xa0", " ").replace("”", "“")
    t = re.sub(r"(^|\s)“", r"\1„", t)
    t = re.sub(r"\s+", " ", t).strip()
    return t


def rechnik():
    data = json.load(open(os.path.join(os.path.dirname(ROOT), "site-src", "rechnik.json"), encoding="utf-8"))
    groups, parent = {}, ""
    for name, cause, cure in data:
        name, cause, cure = clean(name), clean(cause), clean(cure)
        if name[0] in "–-":
            sub = name.lstrip("–- ").strip()
            label = f'{parent} <span class="rx-sub">– {esc(sub)}</span>'
            plain = f"{parent} – {sub}"
        else:
            parent = esc(name)
            label, plain = parent, name
        letter = plain[0].upper()
